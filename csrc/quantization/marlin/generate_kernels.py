    *[("kS8", "kU4", "kBFloat16", 256, 1, 8, 8, g) for g in (2, 4)],
    *[("kS8", "kU4", "kBFloat16", 256, m, 16, 4, g) for g in (2, 4) for m in (2, 3, 4)],
